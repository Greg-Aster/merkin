function createObservatoryWalkableMeshChunkEntries(): readonly CollisionCookDraftEntryData[] {
	const chunksPerAxis =
		(observatoryWalkableMeshGridSize - 1) /
		observatoryWalkableMeshChunkCellSpan;

	if (!Number.isInteger(chunksPerAxis)) {
		throw new Error(
			"Observatory walkable mesh chunk size must evenly divide the authored height grid.",
		);
	}

	const entries: CollisionCookDraftEntryData[] = [];

	for (let zChunk = 0; zChunk < chunksPerAxis; zChunk += 1) {
		for (let xChunk = 0; xChunk < chunksPerAxis; xChunk += 1) {
			const chunkId = `x${xChunk}-z${zChunk}`;

			entries.push({
				id: `observatory-walkable-mesh-chunk-${chunkId}`,
				stableId: `observatory:walkable-mesh:chunk:${chunkId}`,
				prefabId: "observatory_walkable_mesh",
				colliderTarget:
					xChunk === 0 && zChunk === 0 ? "prefab" : "level-instance",
				collider: {
					intent: "walkable",
					channel: "worldStatic",
					shape: createObservatoryWalkableMeshChunkShape({
						startXIndex: xChunk * observatoryWalkableMeshChunkCellSpan,
						startZIndex: zChunk * observatoryWalkableMeshChunkCellSpan,
					}),
				},
				readiness: {
					requiredCollision: true,
					requiredWalkable: true,
					terrainPackageOwned: true,
				},
				notes:
					"Deterministic GLB-footprint walkable mesh chunk derived from the authored Observatory environment surface.",
			});
		}
	}

	return entries;
}

function createObservatoryWalkableMeshChunkShape(options: {
	readonly startXIndex: number;
	readonly startZIndex: number;
}): CollisionCookDraftEntryData["collider"]["shape"] {
	const vertices: Array<[number, number, number]> = [];
	const indices: number[] = [];
	const vertexIndicesByGridCoordinate = new Map<string, number>();

	function addVertex(xIndex: number, zIndex: number): number {
		const key = `${xIndex}:${zIndex}`;
		const existing = vertexIndicesByGridCoordinate.get(key);

		if (existing !== undefined) {
			return existing;
		}

		const row = observatoryWalkableMeshHeightRows[zIndex];

		if (!row) {
			throw new Error(
				`Observatory walkable mesh chunk references missing height row ${zIndex}.`,
			);
		}

		const height = row[xIndex];

		if (height === undefined || height === null) {
			throw new Error(
				`Observatory walkable mesh chunk references missing emitted height sample ${xIndex}, ${zIndex}.`,
			);
		}

		const vertexIndex = vertices.length;
		vertexIndicesByGridCoordinate.set(key, vertexIndex);
		vertices.push([
			observatoryWalkableMeshCoordinate(xIndex),
			height,
			observatoryWalkableMeshCoordinate(zIndex),
		]);

		return vertexIndex;
	}

	for (
		let zIndex = options.startZIndex;
		zIndex < options.startZIndex + observatoryWalkableMeshChunkCellSpan;
		zIndex += 1
	) {
		for (
			let xIndex = options.startXIndex;
			xIndex < options.startXIndex + observatoryWalkableMeshChunkCellSpan;
			xIndex += 1
		) {
			if (!observatoryWalkableMeshCellHasTerrain(xIndex, zIndex)) {
				continue;
			}

			const topLeft = addVertex(xIndex, zIndex);
			const topRight = addVertex(xIndex + 1, zIndex);
			const bottomLeft = addVertex(xIndex, zIndex + 1);
			const bottomRight = addVertex(xIndex + 1, zIndex + 1);

			indices.push(
				topLeft,
				bottomLeft,
				topRight,
				topRight,
				bottomLeft,
				bottomRight,
			);
		}
	}

	if (indices.length === 0) {
		throw new Error(
			`Observatory walkable mesh chunk ${options.startXIndex}:${options.startZIndex} has no source terrain cells.`,
		);
	}

	return {
		type: "mesh",
		vertices,
		indices,
	};
}

function observatoryWalkableMeshCellHasTerrain(
	xIndex: number,
	zIndex: number,
): boolean {
	const topRow = observatoryWalkableMeshHeightRows[zIndex];
	const bottomRow = observatoryWalkableMeshHeightRows[zIndex + 1];

	return (
		topRow?.[xIndex] !== undefined &&
		topRow[xIndex] !== null &&
		topRow[xIndex + 1] !== undefined &&
		topRow[xIndex + 1] !== null &&
		bottomRow?.[xIndex] !== undefined &&
		bottomRow[xIndex] !== null &&
		bottomRow[xIndex + 1] !== undefined &&
		bottomRow[xIndex + 1] !== null
	);
}

function observatoryWalkableMeshCoordinate(index: number): number {
	return (
		-observatoryWalkableMeshHalfExtent + index * observatoryWalkableMeshCellSize
	);
}

